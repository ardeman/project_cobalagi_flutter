// Writes a promo video's YouTube text (title, description and every upload
// setting) from tool/marketing/youtube.json, ready to paste. Called by
// tool/marketing/lib.sh when it finishes a video:
//   dart run tool/marketing/youtube_text.dart <video> <out.txt>
// where <video> is the file name without .mp4 (promo-en, short-id, ...).
// The title carries the app's version name from pubspec.yaml; STORE=live
// swaps "Coming soon" for the Google Play link.
import 'dart:convert';
import 'dart:io';

/// YouTube's limits.
const titleLimit = 100;
const descriptionLimit = 5000;

Map<String, Object?> loadCopy() =>
    jsonDecode(File('tool/marketing/youtube.json').readAsStringSync())
        as Map<String, Object?>;

/// The version name in pubspec.yaml, e.g. 2.1.0 from `version: 2.1.0+15`.
String appVersion() {
  final match = RegExp(
    r'^version:\s*([^+\s]+)',
    multiLine: true,
  ).firstMatch(File('pubspec.yaml').readAsStringSync());
  if (match == null) throw StateError('No version in pubspec.yaml');
  return match[1]!;
}

/// The videos the copy covers, e.g. promo-en.
List<String> videos(Map<String, Object?> copy) =>
    (copy['videos']! as Map<String, Object?>).keys.toList();

/// The title of [video], with [version] filled in.
String titleOf(Map<String, Object?> copy, String video, String version) {
  final raw = _video(copy, video)['title']! as String;
  if (!raw.contains('{version}')) {
    throw StateError('The title of $video must include {version}');
  }
  return raw.replaceAll('{version}', version);
}

/// The description of [video], with the store line for [live].
String descriptionOf(Map<String, Object?> copy, String video, bool live) {
  final store =
      (copy['store']! as Map<String, Object?>)[live ? 'live' : 'soon']!
          as Map<String, Object?>;
  return (_video(copy, video)['description']! as String).replaceAll(
    '{store}',
    store[_lang(video)]! as String,
  );
}

/// The whole text for [video]: title, description and the settings.
String youtubeText(
  Map<String, Object?> copy,
  String video, {
  required String version,
  required bool live,
}) {
  final kind = video.split('-').first; // promo or short
  final lang = _lang(video);
  final language = _video(copy, video)['language']! as String;
  String fill(String text) => text
      .replaceAll('{lang}', lang)
      .replaceAll('{video}', video)
      .replaceAll('{language}', language)
      .replaceAll('{tags}', copy['tags']! as String);
  final settings = StringBuffer();
  for (final row in (copy['settings']! as List).cast<Map<String, Object?>>()) {
    final choice = (row[kind] ?? row['all']) as String?;
    if (choice == null) continue;
    settings.writeln('- ${row['setting']}: ${fill(choice)}');
    // A reason is one text, or one per kind of video.
    final why = switch (row['why']) {
      final String text => text,
      final Map<String, Object?> byKind => byKind[kind] as String?,
      _ => null,
    };
    if (why != null) settings.writeln('  (${fill(why)})');
  }
  return '''
$video.mp4 · Coba Lagi $version · ${live ? 'on Google Play' : 'coming soon'}
Generated by tool/marketing/youtube_text.dart from youtube.json; don't edit.
YouTube can't replace a video's file: to update one, delete it and upload
the new one.

TITLE
${titleOf(copy, video, version)}

DESCRIPTION
${descriptionOf(copy, video, live)}

SETTINGS
$settings''';
}

Map<String, Object?> _video(Map<String, Object?> copy, String video) {
  final entry = (copy['videos']! as Map<String, Object?>)[video];
  if (entry == null) throw ArgumentError('No YouTube text for $video');
  return entry as Map<String, Object?>;
}

String _lang(String video) => video.split('-').last;

void main(List<String> args) {
  if (args.length != 2) {
    stderr.writeln(
      'Usage: dart run tool/marketing/youtube_text.dart <video> <out.txt>',
    );
    exit(64);
  }
  final live = Platform.environment['STORE'] == 'live';
  File(args[1]).writeAsStringSync(
    youtubeText(loadCopy(), args[0], version: appVersion(), live: live),
  );
}
